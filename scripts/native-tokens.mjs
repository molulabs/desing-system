// Builds tokens/native.js (and its .d.ts) from the tokens/*.css that styles.css imports, so React
// Native reads the same values the web does, and tokens/native-icons.js, the code point of each
// Tabler icon in tokens/icons.css. The CSS stays the source: design-sync and Claude Design read
// and write it.
//
//   node scripts/native-tokens.mjs          writes the files
//   node scripts/native-tokens.mjs --check  fails if they are out of date

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUTPUT = join(ROOT, 'tokens/native.js');
const OUTPUT_TYPES = join(ROOT, 'tokens/native.d.ts');
const OUTPUT_ICONS = join(ROOT, 'tokens/native-icons.js');

export const DEFAULT_THEME = 'campo';
export const DEFAULT_DENSITY = 'touch';

/** The density :root carries when no data-density is set. */
const ROOT_DENSITY = 'compact';

const HEADER = '// Generated by scripts/native-tokens.mjs from tokens/*.css. Do not edit: change the CSS and run `npm run tokens:native`.';

/**
 * The custom properties of each scope: :root, [data-theme="…"] and [data-density="…"].
 *
 * @param {string} css
 */
export function parseScopes(css) {
    const scopes = { root: {}, themes: {}, densities: {} };
    const source = css.replace(/\/\*[\s\S]*?\*\//g, '');

    for (const { selector, body } of topLevelRules(source)) {
        const declarations = customProperties(body);

        if (Object.keys(declarations).length === 0) {
            continue;
        }

        const theme = selector.match(/^\[data-theme="([\w-]+)"\]$/);
        const density = selector.match(/^\[data-density="([\w-]+)"\]$/);

        if (selector === ':root') {
            Object.assign(scopes.root, declarations);
        } else if (theme) {
            scopes.themes[theme[1]] = { ...scopes.themes[theme[1]], ...declarations };
        } else if (density) {
            scopes.densities[density[1]] = { ...scopes.densities[density[1]], ...declarations };
        } else {
            // A token set somewhere else would silently go missing on native
            throw new Error(`Custom properties under "${selector}" have no native equivalent`);
        }
    }

    return scopes;
}

/** Rules at the top level; @-blocks (@font-face, @keyframes…) are skipped whole. */
function* topLevelRules(source) {
    let index = 0;

    while (index < source.length) {
        const open = source.indexOf('{', index);

        if (open === -1) {
            return;
        }

        const selector = source.slice(index, open).replace(/@import[^;]*;/g, '').trim();
        let depth = 1;
        let close = open + 1;

        for (; close < source.length && depth > 0; close++) {
            if (source[close] === '{') depth++;
            if (source[close] === '}') depth--;
        }

        if (!selector.startsWith('@')) {
            yield { selector, body: source.slice(open + 1, close - 1) };
        }

        index = close;
    }
}

function customProperties(body) {
    const declarations = {};

    for (const declaration of body.split(';')) {
        const match = declaration.match(/^\s*--([\w-]+)\s*:\s*([\s\S]+?)\s*$/);

        if (match) {
            declarations[match[1]] = match[2].replace(/\s+/g, ' ');
        }
    }

    return declarations;
}

function resolve(name, context, seen = []) {
    if (seen.includes(name)) {
        throw new Error(`Tokens reference each other in a loop: ${[...seen, name].join(' → ')}`);
    }

    if (!(name in context)) {
        throw new Error(`Unknown token --${name}`);
    }

    return context[name].replace(/var\(\s*--([\w-]+)\s*(?:,\s*([^)]*))?\)/g, (_, ref, fallback) =>
        ref in context || fallback === undefined ? resolve(ref, context, [...seen, name]) : fallback.trim()
    );
}

const PX = /^(-?\d*\.?\d+)px$/;
const NUMBER = /^-?\d*\.?\d+$/;
const COLOR = /^(#[0-9a-f]{3,8}|rgba?\([^)]*\)|transparent)$/i;

/**
 * The value as React Native takes it, or undefined when it only means something on the web
 * (em, ch, %, vw, clamp()).
 *
 * @param {string} value
 */
export function toNative(value) {
    if (PX.test(value)) return Number(value.match(PX)[1]);
    if (NUMBER.test(value)) return Number(value);
    if (COLOR.test(value)) return value;

    const seconds = value.match(/^(\d*\.?\d+)s$/);
    if (seconds) return Math.round(Number(seconds[1]) * 1000);

    // Padding shorthand: [all] | [vertical, horizontal] | [top, horizontal, bottom] | [top, right, bottom, left]
    const parts = value.split(' ');
    if (parts.length > 1 && parts.length <= 4 && parts.every((part) => PX.test(part) || part === '0')) {
        return parts.map((part) => Number(part.replace('px', '')));
    }

    const border = value.match(/^(\d*\.?\d+)px (solid|dashed|dotted) (.+)$/);
    if (border && COLOR.test(border[3])) {
        return { width: Number(border[1]), style: border[2], color: border[3] };
    }

    // Easing.bezier(x1, y1, x2, y2)
    const bezier = value.match(/^cubic-bezier\(([^)]*)\)$/);
    if (bezier) return bezier[1].split(',').map(Number);

    // A font stack: React Native takes one family, the first
    const family = value.match(/^"([^"]+)"/);
    if (family) return family[1];

    // React Native's boxShadow takes the CSS syntax
    if (/^(-?\d*\.?\d+(px)? ){2,3}(-?\d*\.?\d+px )?rgba?\([^)]*\)$/.test(value)) return value;

    return undefined;
}

const camel = (name) => name.replace(/-([a-z0-9])/g, (_, char) => char.toUpperCase());

/**
 * Every theme with every density, resolved and converted. Themes carry the tokens a density
 * never changes, densities the ones it does: a token of one that varied with the other could not
 * be split that way, so it fails instead.
 *
 * @param {string} css
 */
export function buildNativeTokens(css) {
    const scopes = parseScopes(css);
    const themeNames = [DEFAULT_THEME, ...Object.keys(scopes.themes)];
    const densityNames = Object.keys(scopes.densities);
    const densityKeys = new Set(densityNames.flatMap((density) => Object.keys(scopes.densities[density])));
    const webOnly = new Set();

    const table = (theme, density) => {
        const context = { ...scopes.root, ...scopes.themes[theme], ...scopes.densities[density] };
        const values = {};

        for (const name of Object.keys(context)) {
            const value = toNative(resolve(name, context));

            if (value === undefined) {
                webOnly.add(name);
            } else {
                values[name] = value;
            }
        }

        return values;
    };

    const tables = Object.fromEntries(
        themeNames.map((theme) => [theme, Object.fromEntries(densityNames.map((density) => [density, table(theme, density)]))])
    );

    // Web only wherever it is: every theme and density keep the same keys
    for (const densitiesOfTheme of Object.values(tables)) {
        for (const values of Object.values(densitiesOfTheme)) {
            webOnly.forEach((name) => delete values[name]);
        }
    }

    const pick = (values, keep) =>
        Object.fromEntries(Object.entries(values).filter(([name]) => keep(name)).map(([name, value]) => [camel(name), value]));
    const same = (a, b) => JSON.stringify(a) === JSON.stringify(b);

    const themes = {};
    for (const theme of themeNames) {
        themes[theme] = pick(tables[theme][ROOT_DENSITY], (name) => !densityKeys.has(name));

        for (const density of densityNames) {
            if (!same(themes[theme], pick(tables[theme][density], (name) => !densityKeys.has(name)))) {
                throw new Error(`A token of the "${theme}" theme changes with the "${density}" density`);
            }
        }
    }

    const densities = {};
    for (const density of densityNames) {
        densities[density] = pick(tables[DEFAULT_THEME][density], (name) => densityKeys.has(name));

        for (const theme of themeNames) {
            if (!same(densities[density], pick(tables[theme][density], (name) => densityKeys.has(name)))) {
                throw new Error(`A token of the "${density}" density changes with the "${theme}" theme`);
            }
        }
    }

    return { themes, densities, webOnly: [...webOnly].sort() };
}

/**
 * The code point of each icon class, without its "ti-": the Tabler font draws it as that
 * character.
 *
 * @param {string} css
 */
export function buildIconGlyphs(css) {
    const glyphs = {};

    for (const [, name, code] of css.matchAll(/\.ti-([\w-]+):before\s*\{\s*content:\s*"\\([0-9a-f]+)"\s*\}/gi)) {
        glyphs[name] = parseInt(code, 16);
    }

    if (Object.keys(glyphs).length === 0) {
        throw new Error('No Tabler icon found in tokens/icons.css');
    }

    return glyphs;
}

export function renderIcons(glyphs) {
    return `${HEADER}
//
// The code point of each Tabler icon, by its class without "ti-": String.fromCodePoint(glyphs.plus)
// drawn in the tabler-icons font is <i className="ti ti-plus" />.

export const glyphs = ${JSON.stringify(glyphs)};
`;
}

/** The CSS styles.css imports, in its order. */
export function readTokenCss() {
    const entry = readFileSync(join(ROOT, 'styles.css'), 'utf8');
    const files = [...entry.matchAll(/@import\s+url\("([^"]+)"\)/g)].map((match) => match[1]);

    return files.map((file) => readFileSync(join(ROOT, file), 'utf8')).join('\n');
}

const typeOf = (value) => {
    if (typeof value === 'number' || typeof value === 'string') return typeof value;
    if (Array.isArray(value)) return 'number[]';

    return `{ ${Object.entries(value).map(([key, field]) => `${key}: ${typeof field}`).join('; ')} }`;
};

const interfaceOf = (name, values) =>
    `export interface ${name} {\n${Object.entries(values).map(([key, value]) => `    ${key}: ${typeOf(value)};`).join('\n')}\n}`;

/** JSON with each token on its line, and its array or border on that same line. */
const json = (tokensByName) =>
    `{\n${Object.entries(tokensByName)
        .map(
            ([name, tokens]) =>
                `    ${JSON.stringify(name)}: {\n${Object.entries(tokens)
                    .map(([key, value]) => `        ${JSON.stringify(key)}: ${JSON.stringify(value)}`)
                    .join(',\n')}\n    }`
        )
        .join(',\n')}\n}`;

export function render({ themes, densities, webOnly }) {

    const js = `${HEADER}
//
// Lengths are numbers (px), durations milliseconds, paddings arrays in CSS shorthand order,
// borders { width, style, color }, easings the four Easing.bezier numbers and shadows the CSS
// string React Native's boxShadow takes. Line heights stay multipliers of the font size.
// Web only, left out: ${webOnly.map((name) => `--${name}`).join(', ')}.

export const themes = ${json(themes)};

export const densities = ${json(densities)};

/**
 * The tokens of one theme in one density, as the web resolves them under
 * data-theme and data-density.
 */
export function nativeTokens({ theme = '${DEFAULT_THEME}', density = '${DEFAULT_DENSITY}' } = {}) {
    return { ...themes[theme], ...densities[density] };
}
`;

    const types = `${HEADER}

export type ThemeName = ${Object.keys(themes).map((theme) => `'${theme}'`).join(' | ')};
export type DensityName = ${Object.keys(densities).map((density) => `'${density}'`).join(' | ')};

${interfaceOf('ThemeTokens', themes[DEFAULT_THEME])}

${interfaceOf('DensityTokens', densities[DEFAULT_DENSITY])}

export type NativeTokens = ThemeTokens & DensityTokens;

export declare const themes: Record<ThemeName, ThemeTokens>;
export declare const densities: Record<DensityName, DensityTokens>;

/** The tokens of one theme in one density. Defaults: the "${DEFAULT_THEME}" theme, "${DEFAULT_DENSITY}" density. */
export declare function nativeTokens(options?: { theme?: ThemeName; density?: DensityName }): NativeTokens;
`;

    return { js, types };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
    const { js, types } = render(buildNativeTokens(readTokenCss()));
    const icons = renderIcons(buildIconGlyphs(readFileSync(join(ROOT, 'tokens/icons.css'), 'utf8')));

    if (process.argv.includes('--check')) {
        const current = (file) => {
            try {
                return readFileSync(file, 'utf8');
            } catch {
                return null;
            }
        };

        if (current(OUTPUT) !== js || current(OUTPUT_TYPES) !== types || current(OUTPUT_ICONS) !== icons) {
            console.error('tokens/native.js is out of date: run `npm run tokens:native`.');
            process.exit(1);
        }
    } else {
        writeFileSync(OUTPUT, js);
        writeFileSync(OUTPUT_TYPES, types);
        writeFileSync(OUTPUT_ICONS, icons);
    }
}
